export function sampleStatsFor(cats?: number, housing?: string): Stats[] {
  if (cats == null && !housing) return SAMPLE_STATS;
  const ratio = (cats === 1 ? 0.45 : cats === 2 ? 0.35 : cats === 3 ? 0.2 : 1)
    * (housing === 'studio' ? 0.35 : housing === 'apartment' ? 0.45 : housing === 'house' ? 0.2 : 1);
  return SAMPLE_STATS.map((row) => {
    const n_verified = Math.max(2, Math.round(row.n_verified * ratio));
    const n_households = Math.max(2, Math.round(row.n_households * ratio));
    const odorShift =
      housing === 'studio' && row.product_id === 'pidan-mixed' ? -0.5 :
      housing === 'studio' && (row.product_id === 'everclean-blue' || row.product_id === 'odout-tofu') ? 0.2 : 0;
    const dropCost = cats === 3 && housing === 'house' && row.product_id === 'lady-n-tofu';
    return {
      ...row,
      n_verified,
      n_households,
      dust_w: Math.max(2, Math.round(row.dust_w * ratio)),
      odor: row.odor != null ? Math.min(5, Math.max(1, Number((row.odor + odorShift).toFixed(1)))) : null,
      odor_w: Math.max(2, Math.round(row.odor_w * ratio)),
      cost_per_cat_day: dropCost ? null : row.cost_per_cat_day,
    };
  });
}

